    private void seguir() {
            if(nombre != null && mazoSeleccionado != -1) {
                Mazo mazo = new CatalogoCartas().crearMazoPredefinido(mazoSeleccionado);
                ZonaEnergia zonaEnergia = new ZonaEnergia(mazo.getTiposEnergia());
                Jugador jugador = new Jugador(nombre, mazo, zonaEnergia);
                if(jugador1 == null) {
                    new JugadorInformacion((byte) 2, jugador).setVisible(true);
                    this.dispose();
                } else {
                    motorGrafico = new MotorGrafico(jugador1, jugador);
                    continuar();
                    this.dispose();
                }
            }
    }


