    private void mostrarMano(java.util.List<modelo.Carta> mano) {
    panelMano.removeAll();                       // limpia la mano anterior
    panelMano.setLayout(new java.awt.FlowLayout(java.awt.FlowLayout.CENTER, 4, 0));
    panelMano.setOpaque(false);

    for (modelo.Carta carta : mano) {
        javax.swing.JLabel lbl = new javax.swing.JLabel(carta.getNombre(),
                                                        javax.swing.SwingConstants.CENTER);
        lbl.setPreferredSize(new java.awt.Dimension(50, 70));
        lbl.setOpaque(true);
        lbl.setBackground(java.awt.Color.WHITE);
        lbl.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.DARK_GRAY));
        panelMano.add(lbl);
    }

    panelMano.revalidate();   // recalcula el layout
    panelMano.repaint();      // redibuja
}
private void probarMano(int cantidad) {
    java.util.List<String> nombres = new java.util.ArrayList<>();
    for (int i = 1; i <= cantidad; i++) nombres.add("Carta " + i);

    panelMano.removeAll();
    panelMano.setLayout(new java.awt.FlowLayout(java.awt.FlowLayout.CENTER, 4, 0));
    panelMano.setOpaque(false);

    for (String n : nombres) {
        javax.swing.JLabel lbl = new javax.swing.JLabel(n, javax.swing.SwingConstants.CENTER);
        lbl.setPreferredSize(new java.awt.Dimension(50, 70));
        lbl.setOpaque(true);
        lbl.setBackground(java.awt.Color.WHITE);
        lbl.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.DARK_GRAY));
        panelMano.add(lbl);
    }
    panelMano.revalidate();
    panelMano.repaint();
}


